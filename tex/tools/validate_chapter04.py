#!/usr/bin/env python3
"""Audit chapter 4 against DOCX, including math, translation coverage and builds."""
from supporting_scope import before_supporting
import hashlib
import json
import re
from extract_pilot import ROOT, nodes
from extract_chapter04 import extract
from validate_pilot import prose, normalize
from validate_spanish import paragraphs, parse


def math_content(text):
    """Ignore reviewed typesetting differences, but retain math tokens and values."""
    for es, en in [('intensidad relativa de la', 'relative strength of'),
                   ('curvatura del espaciotiempo', 'spacetime curvature'),
                   ('masa de un objeto', 'mass of an object'),
                   ('tamaño de un objeto', 'size of an object')]:
        text = text.replace(es, en)
    text = re.sub(r'\\label\{[^}]+\}', '', text)
    text = text.replace(r'\begin{array}{@{}w{c}{0.2933\linewidth}@{}w{c}{0.2933\linewidth}@{}w{c}{0.2933\linewidth}@{}}', '')
    text = re.sub(r'\\begin\{array\}\{c@\{[^}]+\}c@\{[^}]+\}c\}', '', text)
    text = re.sub(r'\\(?:begin|end)\{(?:equation|gathered|array)\}', '', text)
    text = text.replace(r'\textcolor{gray}', '').replace(r'\bigodot', r'\odot')
    text = re.sub(r'\\(?:text|mathrm)\{([^}]+)\}', r'\1', text)
    text = text.replace('{,}', '.').replace('6,372', '6372').replace('695,000', '695000')
    text = text.replace(r'\\', '').replace(r'\,', '').replace(r'\ ', '').replace('&', '')
    return re.sub(r'[\s{}]', '', text)


def prose_numbers(text, language):
    text = re.sub(r'\\(?:begin|end)\{(?:figure|description)\}(?:\[[^]]*\])?', '', text)
    text = re.sub(r'\\item\[[^]]*\]', '', text)
    text = text.replace(r'\,', '')
    s = prose(parse(text)['blocks'])
    if language == 'en':
        s = re.sub(r'(?<=\d),(?=\d{3}\b)', '', s)
    else:
        s = s.replace(',', '.')
    return re.findall(r'\d+(?:\.\d+)?', s)


def main():
    extract()  # Refresh only the audit; never overwrite the English chapter.
    directory = ROOT / 'tex/build/ch04-audit'
    source = json.loads((directory / 'source-map.json').read_text())
    en = '\n'.join((ROOT / 'tex/en' / f'{name}.tex').read_text() for name in ('ch04', 'notes/ch04'))
    es = '\n'.join((ROOT / 'tex/spanish' / f'{name}.tex').read_text() for name in ('ch04', 'notes/ch04'))
    expected = []
    for pos, record in source['paragraphs'].items():
        s = record['source_text']
        if pos == '364':
            s = s.removeprefix('4 ')
        if pos in ('374', '381', '412'):
            s = ''  # Equation numbers are generated by LaTeX.
        s = re.sub(r'^Fig\.\s*4\.\d+\s+', '', s)
        expected.append(s)
    t = re.sub(r'\\eqref\{eq:04-(\d+)\}', lambda m: f'(4.{int(m[1])})', en)
    t = re.sub(r'\\ref\{fig:04-(\d+)\}', lambda m: f'4.{int(m[1])}', t)
    t = re.sub(r'\\section\*\{Chapter 4:[^}]+\}', '', t)
    a, b = normalize(''.join(expected)), normalize(prose(parse(t)['blocks']))
    if a != b:
        i = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
        raise AssertionError(f'English differs from DOCX at {i}:\n{a[max(0,i-50):i+100]}\n{b[max(0,i-50):i+100]}')
    enp, esp = paragraphs(en), paragraphs(es)
    assert list(enp) == list(esp) == list(source['paragraphs']), 'Paragraph coverage/order'
    for command in ('label', 'ref', 'eqref', 'hyperlink', 'hypertarget'):
        pattern = r'\\' + command + r'\{([^}]+)\}'
        assert re.findall(pattern, en) == re.findall(pattern, es), command
    assert en.count(r'\index{') == es.count(r'\index{') == len(source['index_entries']) == 49
    assert en.count(r'\caption{') == es.count(r'\caption{') == 2
    assert en.count(r'\begin{equation}') == es.count(r'\begin{equation}') == 3
    assert en.count(r'\hypertarget{note:') == es.count(r'\hypertarget{note:') == 3
    pattern = r'\\includegraphics\[[^]]+\]\{([^}]+)\}'
    assert re.findall(pattern, en) == re.findall(pattern, es)
    assert re.findall(pattern.replace('([^}]+)', '[^}]+'), en) == re.findall(pattern.replace('([^}]+)', '[^}]+'), es)
    for path in re.findall(pattern, en):
        assert (ROOT / 'tex' / path).is_file(), path
    em = [m['c'][1] for m in nodes(parse(en), 'Math')]
    sm = [m['c'][1] for m in nodes(parse(es), 'Math')]
    original = [m for m in source['math'] if m.strip()]
    assert len(em) == len(original) == 8
    assert len(sm) == 9  # The source's literal '8' in note 2 is the solar-symbol typo.
    for i, (a, b) in enumerate(zip(original, em)):
        assert math_content(a) == math_content(b), ('source math', i, math_content(a), math_content(b))
    for i, (a, b) in enumerate(zip(em, sm)):
        assert math_content(a) == math_content(b), ('translated math', i, math_content(a), math_content(b))
    assert sm[-1] == r'\odot'
    # Check prose numbers paragraph by paragraph; equations are checked above.
    errors = []
    for pos in enp:
        a, b = enp[pos], esp[pos]
        if pos == '415':
            # English short scale: 1,000 billion^3 -> un millón de billones de billones;
            # 1,000 billion solar masses -> un billón de masas solares.
            a = a.replace('1,000 billion billion billion', 'un millón de billones de billones')
            a = a.replace('1,000 billion', 'un billón')
        if pos == '2033':
            a = a.replace('symbol 8,', 'symbol,')
        if pos == '2034':
            a = a.replace('10,000 billion', 'diez billones').replace('30,000 billion', 'treinta billones')
        if prose_numbers(a, 'en') != prose_numbers(b, 'es'):
            errors.append((pos, prose_numbers(a, 'en'), prose_numbers(b, 'es')))
    assert not errors, errors
    logs = {}
    for build, lang in [('chapter04', 'en'), ('spanish-chapter04', 'spanish')]:
        base = ROOT / 'tex/build' / build / 'chapter04'
        log = base.with_suffix('.log').read_text()
        issues = re.findall(r'.*(?:Warning|Overfull|Underfull|Missing character|undefined|unreferenced destination).*', log)
        assert not issues, '\n'.join(issues)
        idx = base.with_suffix('.ilg').read_text()
        assert '49 entries accepted, 0 rejected' in idx and '0 warnings' in idx
        inputs = [ROOT / f'tex/{lang}/{f}.tex' for f in ('ch04', 'notes/ch04', 'chapter04')]
        inputs += [ROOT / 'tex/common/preamble.tex']
        inputs += [ROOT / 'tex' / p for p in re.findall(pattern, en)]
        assert all(p.stat().st_mtime <= base.with_suffix('.pdf').stat().st_mtime for p in inputs), 'Stale PDF'
        logs[build] = 'clean'
    snapshot = json.loads((directory / 'protected-before.json').read_text())
    for name, digest in snapshot.items():
        data = (ROOT / name).read_bytes()
        data = before_supporting(name, data)
        if name in ('tex/en/main.tex', 'tex/spanish/main.tex'):
            lang = name.split('/')[1]
            for chapter in ('04', '05', '06', '07', '08'):
                data = data.replace(f'\\include{{{lang}/ch{chapter}}}\n'.encode(), b'').replace(f'\\input{{{lang}/notes/ch{chapter}}}\n'.encode(), b'')
        if name == 'figs/manifest.tsv':
            data = b'\n'.join(line for line in data.split(b'\n') if not line.startswith((b'04-', b'05-', b'06-', b'07-', b'08-')))
        assert hashlib.sha256(data).hexdigest() == digest, f'Protected file changed: {name}'
    result = {'english_matches_docx': True, 'paragraphs': len(enp), 'figures': 2,
              'numbered_equations': 3, 'figure_formula_rows': 2, 'notes': 3,
              'source_math_objects': len(source['math']), 'nonempty_source_math_objects': len(original),
              'index_entries': 49, 'builds': logs, 'protected_files_checked': len(snapshot),
              'exceptions': ['Spanish note 2: literal 8 corrected to solar symbol; see editorial summary',
                             'English short-scale numbers translated into Spanish long scale'],
              'scope': 'Mechanical checks complement manual translation and visual review.'}
    (directory / 'validation.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
